import { randomUUID } from 'node:crypto'
import { test, expect, type APIRequestContext, type Page } from '@playwright/test'

const password = 'QA-ephemeral-password-2026!'
async function register(page: Page, username: string, displayName: string) {
  await page.goto('/register')
  await page.getByLabel('Votre nom').fill(displayName)
  await page.getByLabel('Nom d’utilisateur').fill(username)
  await page.getByLabel('Adresse email').fill(`${username}@example.test`)
  await page.getByLabel('Mot de passe', { exact: true }).fill(password)
  const registered = page.waitForResponse(r => r.url().endsWith('/api/auth/register') && r.request().method() === 'POST')
  await page.getByRole('button', { name: 'Créer mon compte' }).click()
  expect((await registered).status()).toBe(201)
  await expect(page.getByRole('searchbox')).toBeVisible()
  const me = await page.request.get('/api/auth/me')
  expect(me.status()).toBe(200)
  expect(await me.json()).toMatchObject({ username, displayName })
  await page.reload()
  await expect(page.getByRole('searchbox')).toBeVisible()
}
async function get(api: APIRequestContext, path: string) {
  const response = await api.get(`/api${path}`)
  expect(response.status(), `GET ${path}`).toBe(200)
  return response.json()
}
async function denied(api: APIRequestContext, path: string, method = 'GET', data?: object, status = 404) {
  const response = await api.fetch(`/api${path}`, { method, ...(method === 'GET' ? {} : { data: data ?? {} }) })
  expect(response.status(), `${method} ${path}`).toBe(status)
}

test('profil temporaire réel : création, cookie durable, conversion même id et nouveau profil isolé', async ({ page }) => {
  const suffix = randomUUID().replaceAll('-', '').slice(0, 10)
  const title = `Cartes invité ${suffix}`
  await page.goto('/library')
  await expect(page.getByRole('heading', { name: 'La bibliothèque.' })).toBeVisible()
  await expect(page.getByRole('region', { name: 'Profil temporaire' })).toBeVisible()
  const original = await get(page.request, '/auth/me')
  expect(original.isGuest).toBe(true)
  const cookies = await page.context().cookies()
  expect(cookies.some(cookie => cookie.name !== 'flashcard.sid' && cookie.httpOnly && cookie.expires > Date.now() / 1000 + 390 * 86400)).toBe(true)
  await page.getByRole('link', { name: 'Nouveau paquet', exact: true }).click()
  await page.getByLabel('Titre du paquet').fill(title)
  await page.getByRole('button', { name: 'Ajouter une carte' }).click()
  await page.getByLabel('Question 1', { exact: true }).fill('Qui conserve le contenu ?')
  await page.getByLabel('Réponse 1', { exact: true }).fill('Le même profil après conversion.')
  await page.getByRole('button', { name: 'Enregistrer le paquet', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Paquet enregistré')
  const deck = (await get(page.request, '/decks')).items[0]
  expect(typeof deck.owner === 'string' ? deck.owner : deck.owner._id).toBe(original._id)
  await page.getByRole('link', { name: 'Voir le paquet →' }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  // Restore with the durable guest cookie only, not the session cookie.
  await page.context().clearCookies({ name: 'flashcard.sid' })
  await page.reload()
  await expect(page.getByRole('region', { name: 'Profil temporaire' })).toBeVisible()
  expect((await get(page.request, '/auth/me'))._id).toBe(original._id)
  expect((await get(page.request, `/decks/${deck._id}`)).cards).toHaveLength(1)
  await register(page, `qa_g_${suffix}`, 'Invité conservé QA')
  expect(await get(page.request, '/auth/me')).toMatchObject({ _id: original._id, isGuest: false })
  await expect(page.getByRole('region', { name: 'Profil temporaire' })).toHaveCount(0)
  await page.goto('/library')
  await page.getByRole('button', { name: 'Paquets', exact: true }).click()
  await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
  await page.goto(`/profile/qa_g_${suffix}`)
  await expect(page.getByRole('heading', { name: 'Invité conservé QA', exact: true })).toBeVisible()
  await page.locator('main').getByRole('button', { name: 'Quitter ce profil' }).click()
  await expect(page).toHaveURL(/\/login$/)
  expect((await page.request.get('/api/auth/me')).status()).toBe(401)
  await page.getByRole('button', { name: 'Recommencer en invité' }).click()
  await expect(page.getByRole('region', { name: 'Profil temporaire' })).toBeVisible()
  const fresh = await get(page.request, '/auth/me')
  expect(fresh.isGuest).toBe(true); expect(fresh._id).not.toBe(original._id)
  expect((await get(page.request, '/decks')).items).toEqual([])
  await denied(page.request, `/decks/${deck._id}`)
})

test('deux comptes réels : organisation, cartes, révision, publication, social et confidentialité', async ({ page: alice, browser, baseURL, playwright }) => {
  const suffix = randomUUID().replaceAll('-', '').slice(0, 10)
  const author = `qa_a_${suffix}`, reader = `qa_b_${suffix}`
  const title = `Photosynthèse QA ${suffix}`
  const bobContext = await browser.newContext({ baseURL })
  const bob = await bobContext.newPage()
  const anonymous = await playwright.request.newContext({ baseURL })
  const pageErrors: string[] = []
  alice.on('pageerror', error => pageErrors.push(error.message))
  bob.on('pageerror', error => pageErrors.push(error.message))
  let courseId = '', chapterId = '', deckId = '', publicationId = '', cardId = ''
  try {
    await test.step('Services réels, inscription UI A et restauration de session Mongo', async () => {
      expect(await get(alice.request, '/ready')).toEqual({ status: 'ok', connected: true })
      expect((await anonymous.get('/api/auth/me')).status()).toBe(401)
      const preflight = await alice.request.fetch('http://127.0.0.1:3001/api/decks', {
        method: 'OPTIONS', headers: { Origin: baseURL!, 'Access-Control-Request-Method': 'POST' },
      })
      expect(preflight.status()).toBe(204)
      expect(preflight.headers()['access-control-allow-origin']).toBe(baseURL)
      expect(preflight.headers()['access-control-allow-credentials']).toBe('true')
      await register(alice, author, 'Alice QA')
      const cookies = await alice.context().cookies()
      expect(cookies.find(cookie => cookie.name === 'flashcard.sid')).toMatchObject({ httpOnly: true, sameSite: 'Lax' })
    })

    await test.step('UI A : créer cours, chapitre et paquet privé avec deux cartes', async () => {
      await alice.goto('/library')
      await alice.getByRole('button', { name: 'Nouveau cours', exact: true }).click()
      await alice.getByLabel('Titre', { exact: true }).fill('Botanique QA')
      await alice.getByRole('button', { name: 'Enregistrer', exact: true }).click()
      await alice.getByRole('button', { name: 'Botanique QA', exact: true }).click()
      await alice.getByRole('button', { name: 'Ajouter un chapitre' }).click()
      await alice.getByLabel('Titre', { exact: true }).fill('Énergie lumineuse QA')
      await alice.getByRole('button', { name: 'Enregistrer', exact: true }).click()
      await alice.getByRole('button', { name: /1 Énergie lumineuse QA/ }).click()
      const courses = await get(alice.request, '/courses')
      expect(courses.items).toHaveLength(1)
      courseId = courses.items[0]._id
      const chapters = await get(alice.request, `/courses/${courseId}/chapters`)
      expect(chapters.items).toHaveLength(1)
      chapterId = chapters.items[0]._id
      await alice.getByRole('link', { name: 'Nouveau paquet', exact: true }).click()
      await expect(alice.getByLabel('Chapitre', { exact: true })).toHaveValue(chapterId)
      await alice.getByLabel('Titre du paquet').fill(title)
      for (const [index, [front, back]] of [
        ['Quel pigment capte la lumière ?', 'La chlorophylle.'],
        ['Quel gaz est libéré ?', 'Le dioxygène.'],
      ].entries()) {
        await alice.getByRole('button', { name: 'Ajouter une carte' }).click()
        await alice.getByLabel(`Question ${index + 1}`, { exact: true }).fill(front!)
        await alice.getByLabel(`Réponse ${index + 1}`, { exact: true }).fill(back!)
      }
      await alice.getByRole('button', { name: 'Monter la carte 2' }).click()
      await alice.getByRole('button', { name: 'Enregistrer le paquet', exact: true }).click()
      await expect(alice.getByRole('status')).toContainText('Paquet enregistré')
      await alice.getByRole('link', { name: 'Voir le paquet →' }).click()
      await expect(alice.getByRole('heading', { name: title, exact: true })).toBeVisible()
      deckId = new URL(alice.url()).pathname.split('/').at(-1)!
      const deck = await get(alice.request, `/decks/${deckId}`)
      expect(deck).toMatchObject({ chapter: chapterId, visibility: 'private', cardCount: 2 })
      expect(deck.cards.map((card: { front: string }) => card.front)).toEqual(['Quel gaz est libéré ?', 'Quel pigment capte la lumière ?'])
      cardId = deck.cards[0]._id
    })

    await test.step('UI B : compte indépendant ; paquet privé inaccessible et écritures étrangères refusées', async () => {
      await register(bob, reader, 'Bob QA')
      expect((await get(alice.request, '/auth/me')).username).toBe(author)
      expect((await get(bob.request, '/auth/me')).username).toBe(reader)
      expect((await get(bob.request, '/courses')).items).toEqual([])
      expect((await get(bob.request, '/decks')).items).toEqual([])
      await denied(bob.request, `/decks/${deckId}`)
      await denied(anonymous, `/decks/${deckId}`)
      await denied(bob.request, `/decks/${deckId}`, 'PATCH', { title: 'Interdit' })
      await denied(bob.request, `/cards/${cardId}`, 'PATCH', { back: 'Interdit' })
      await denied(bob.request, `/courses/${courseId}/chapters`)
      await denied(bob.request, `/decks/${deckId}/save`, 'PUT', { saved: true })
      await denied(bob.request, `/decks/${deckId}/publish`, 'POST')
      await denied(bob.request, `/decks/${deckId}/study-sessions`, 'POST', { cardsVisited: 1, durationSeconds: 1 })
      await denied(bob.request, `/profiles/${author}`, 'PATCH', { bio: 'Interdit' }, 403)
      expect((await get(bob.request, `/feed?q=${suffix}`)).items).toEqual([])
      expect((await get(bob.request, `/profiles/${author}`)).decks).toEqual([])
      await bob.goto(`/decks/${deckId}`)
      await expect(bob.getByRole('alert')).toBeVisible()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
    })

    await test.step('UI A : réviser recto-verso puis vérifier une seule session persistée', async () => {
      await alice.getByRole('link', { name: 'Réviser ce paquet' }).click()
      await alice.getByRole('button', { name: 'Commencer la révision' }).click()
      await alice.locator('main').focus()
      await alice.keyboard.press('Space')
      await expect(alice.getByText('Le dioxygène.', { exact: true })).toBeVisible()
      await alice.keyboard.press('ArrowRight')
      await expect(alice.getByText('Quel pigment capte la lumière ?', { exact: true })).toBeVisible()
      await alice.getByRole('button', { name: 'Terminer', exact: true }).click()
      await expect(alice.getByText('Session enregistrée dans votre historique.')).toBeVisible()
      await alice.reload()
      const history = await get(alice.request, '/study-sessions')
      expect(history.items).toHaveLength(1)
      expect(history.items[0]).toMatchObject({ deck: deckId, cardsVisited: 2 })
      expect(history.items[0].durationSeconds).toBeGreaterThanOrEqual(1)
      expect((await get(bob.request, '/study-sessions')).items).toEqual([])
    })

    await test.step('UI A : publier ; UI B : rechercher, aimer, enregistrer, consulter le profil', async () => {
      await alice.goto(`/decks/${deckId}`)
      await alice.getByRole('button', { name: 'Publier', exact: true }).click()
      await expect(alice.getByRole('status')).toContainText('maintenant publié')
      await bob.goto('/feed')
      await bob.getByRole('searchbox').fill(suffix)
      await expect(bob.getByRole('heading', { name: title, exact: true })).toBeVisible()
      await bob.getByRole('button', { name: 'Aimer ce paquet', exact: true }).click()
      await expect(bob.getByRole('button', { name: 'Ne plus aimer', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await bob.getByRole('button', { name: 'Enregistrer', exact: true }).click()
      await expect(bob.getByRole('button', { name: 'Enregistré', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await bob.reload()
      await expect(bob.getByRole('button', { name: 'Ne plus aimer', exact: true })).toHaveAttribute('aria-pressed', 'true')
      await expect(bob.getByRole('button', { name: 'Enregistré', exact: true })).toHaveAttribute('aria-pressed', 'true')
      const feed = await get(bob.request, `/feed?q=${suffix}`)
      expect(feed.items).toHaveLength(1)
      expect(feed.items[0]).toMatchObject({ likeCount: 1, liked: true, saved: true, deck: { _id: deckId, cardCount: 2 } })
      publicationId = feed.items[0]._id
      await bob.goto('/library')
      await bob.getByRole('button', { name: 'Enregistrés', exact: true }).click()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toBeVisible()
      expect((await get(bob.request, '/saved')).items.map((deck: { _id: string }) => deck._id)).toEqual([deckId])
      await bob.goto(`/profile/${author}`)
      await expect(bob.getByRole('heading', { name: 'Alice QA', exact: true })).toBeVisible()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toBeVisible()
      await expect(bob.getByRole('button', { name: 'Modifier mon profil' })).toHaveCount(0)
      const profile = await get(bob.request, `/profiles/${author}`)
      expect(profile.publicDeckCount).toBe(1)
      expect(profile.decks.map((deck: { _id: string }) => deck._id)).toEqual([deckId])
      for (const field of ['email', 'passwordHash', 'authVersion', 'resetTokenHash']) expect(profile).not.toHaveProperty(field)
      await bob.goto(`/decks/${deckId}/edit`)
      await expect(bob.getByRole('alert')).toContainText('autre créateur')
      await expect(bob.getByLabel('Titre du paquet')).toHaveCount(0)
      await denied(bob.request, `/decks/${deckId}`, 'DELETE')
      expect((await get(anonymous, `/decks/${deckId}`)).cards).toHaveLength(2)
    })

    await test.step('UI A : dépublier ; disparition fil, sauvegardes, profil et accès direct B/anonyme', async () => {
      await alice.getByRole('link', { name: 'Modifier', exact: true }).click()
      await alice.getByLabel('Visibilité', { exact: true }).selectOption('private')
      await alice.getByRole('button', { name: 'Enregistrer le paquet', exact: true }).click()
      await expect(alice.getByRole('status')).toContainText('Paquet enregistré')
      expect((await get(alice.request, `/decks/${deckId}`)).visibility).toBe('private')
      expect((await get(bob.request, `/feed?q=${suffix}`)).items).toEqual([])
      expect((await get(bob.request, '/saved')).items).toEqual([])
      expect((await get(bob.request, `/profiles/${author}`)).decks).toEqual([])
      await denied(bob.request, `/decks/${deckId}`)
      await denied(anonymous, `/decks/${deckId}`)
      await denied(bob.request, `/publications/${publicationId}/like`, 'PUT', { liked: true })
      await denied(bob.request, `/decks/${deckId}/save`, 'PUT', { saved: true })
      await bob.goto('/feed')
      await bob.getByRole('searchbox').fill(suffix)
      await expect(bob.getByRole('heading', { name: 'La découverte se fait attendre.' })).toBeVisible()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
      await bob.goto('/library')
      await bob.getByRole('button', { name: 'Enregistrés', exact: true }).click()
      await expect(bob.getByRole('heading', { name: 'Gardez vos découvertes à portée de main.' })).toBeVisible()
      await bob.goto(`/profile/${author}`)
      await expect(bob.getByRole('heading', { name: 'Alice QA', exact: true })).toBeVisible()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
      await bob.goto(`/decks/${deckId}`)
      await expect(bob.getByRole('alert')).toBeVisible()
      await expect(bob.getByRole('heading', { name: title, exact: true })).toHaveCount(0)
      expect((await get(alice.request, '/study-sessions')).items).toHaveLength(1)
      expect(pageErrors).toEqual([])
    })
  } finally {
    await anonymous.dispose()
    await bobContext.close()
  }
})